//! `cmd git commit-paths`: commit named paths in a shared checkout and push
//! them, without touching anyone else's uncommitted work in the same tree
//!
//! Many agent threads write into the same working trees, such as research and
//! private-workbench. Plain `git pull --rebase` refuses whenever any tracked
//! file is modified, and stash or autostash would rewrite other threads' files
//! under them, so this rebases in a throwaway worktree and then moves the
//! shared checkout with `git reset --keep`, which refuses rather than
//! overwrite a file with local changes

use std::collections::BTreeSet;
use std::fs;
use std::path::{Component, Path, PathBuf};
use std::thread;
use std::time::Duration;

use clap::Args;
use eyre::{bail, eyre, Result, WrapErr};
use tempfile::TempDir;
use xshell::{cmd, Shell};

/// The commit author name, which the commit guide fixes
const AUTHOR: &str = "Praveen Perera";

/// How long a run waits for another run's lock, in one-second tries
const LOCK_TRIES: u32 = 120;

/// Where identical untracked blockers go, relative to the checkout
const MOVED_DIR: &str = "_scratch/commit-paths-moved";

#[derive(Debug, Clone, Args)]
pub struct CommitPaths {
    /// Files or folders to commit; all must sit in one checkout
    #[arg(required = true)]
    pub paths: Vec<PathBuf>,

    /// Commit message; repeat for body paragraphs
    #[arg(short, long = "message", required = true)]
    pub messages: Vec<String>,

    /// Fetch, then print what would happen; change nothing else
    #[arg(short = 'n', long)]
    pub dry_run: bool,
}

fn say(message: impl AsRef<str>) {
    println!("commit-paths: {}", message.as_ref());
}

pub fn run(sh: &Shell, args: CommitPaths) -> Result<()> {
    let message = Message::new(args.messages)?;
    let (top, rels) = resolve_paths(&args.paths)?;
    let repo = Repo::open(sh, top, args.dry_run)?;

    repo.check_idle()?;

    let _lock = if repo.dry {
        None
    } else {
        Some(Lock::take(&repo)?)
    };

    repo.co
        .git(&["fetch", "--quiet", &repo.upstream.remote])
        .quiet()
        .run()?;

    let ahead = repo
        .co
        .count(&format!("{}..HEAD", repo.upstream.tracking))?;
    if !repo.upstream.on_default && ahead > 0 {
        bail!(
            "{} has {ahead} unpushed commit(s) not made by this run; on a non-default branch \
             this only pushes its own commit",
            repo.upstream.branch
        );
    }

    if ahead > 0 {
        let log = repo.co.read(&[
            "log",
            "--oneline",
            &format!("{}..HEAD", repo.upstream.tracking),
        ])?;
        say(format!(
            "also pushing {ahead} earlier unpushed commit(s) on {}:\n{log}",
            repo.upstream.branch
        ));
    }

    if !repo.upstream.on_default {
        say(format!(
            "{} is not the default branch; pushing to its upstream {}",
            repo.upstream.branch, repo.upstream.name
        ));
    }

    let adopted = repo.clear_blockers(&rels)?;
    repo.commit(&rels, &message)?;
    repo.sync(&adopted)?;

    if !repo.push()? {
        say("push rejected; fetching and rebasing once more");
        repo.co
            .git(&["fetch", "--quiet", &repo.upstream.remote])
            .quiet()
            .run()?;

        let adopted = repo.clear_blockers(&rels)?;
        repo.sync(&adopted)?;

        if !repo.push()? {
            bail!(
                "push failed twice; HEAD {} is committed but NOT pushed",
                repo.co.short_head()
            );
        }
    }

    if repo.dry {
        return Ok(());
    }

    let head = repo.co.rev("HEAD")?;
    if head != repo.co.rev(&repo.upstream.tracking)? {
        bail!(
            "HEAD {} does not match {} after the push",
            repo.co.short_head(),
            repo.upstream.name
        );
    }

    say(format!(
        "pushed {} to {}",
        repo.co.short_head(),
        repo.upstream.name
    ));
    Ok(())
}

/// A validated commit message: the subject first, then body paragraphs
struct Message(Vec<String>);

impl Message {
    fn new(paragraphs: Vec<String>) -> Result<Self> {
        let subject = paragraphs
            .first()
            .ok_or_else(|| eyre!("no message given; pass -m \"<subject>\""))?;

        // the commit guide forbids AI co-author lines and generated-by notes
        let banned = [
            "co-authored-by",
            "generated with",
            "generated by",
            "claude-session:",
        ];
        let lower = paragraphs.join("\n").to_lowercase();
        if banned.iter().any(|needle| lower.contains(needle)) {
            bail!("message has an AI co-author or generated-by line; drop it");
        }

        let chars = subject.chars().count();
        if chars > 50 {
            say(format!(
                "warning: subject is {chars} chars; the guide asks for 50 or fewer"
            ));
        }

        if subject.ends_with('.') {
            say("warning: subject ends with a period");
        }

        Ok(Self(paragraphs))
    }

    fn subject(&self) -> &str {
        &self.0[0]
    }

    fn args(&self) -> Vec<&str> {
        self.0.iter().flat_map(|m| ["-m", m.as_str()]).collect()
    }
}

/// Resolves every path to one checkout's top level and the paths relative to it
fn resolve_paths(paths: &[PathBuf]) -> Result<(PathBuf, Vec<String>)> {
    let mut top: Option<PathBuf> = None;
    let mut rels = Vec::with_capacity(paths.len());

    for path in paths {
        let abs = real_path(path)?;
        let dir = abs
            .ancestors()
            .find(|dir| dir.is_dir())
            .ok_or_else(|| eyre!("{} has no existing parent directory", path.display()))?;

        let found = toplevel(dir)
            .ok_or_else(|| eyre!("{} is not inside a git checkout", path.display()))?;

        if let Some(top) = &top {
            if *top != found {
                bail!(
                    "paths span two checkouts ({} and {}); run once per checkout",
                    top.display(),
                    found.display()
                );
            }
        }

        // committing the whole tree would sweep up other threads' files
        let rel = abs
            .strip_prefix(&found)
            .ok()
            .filter(|rel| !rel.as_os_str().is_empty())
            .ok_or_else(|| {
                eyre!(
                    "refusing {}: name files or folders inside the checkout, not its root",
                    path.display()
                )
            })?;

        let rel = rel
            .to_str()
            .ok_or_else(|| eyre!("{} is not valid UTF-8", path.display()))?;

        rels.push(rel.to_owned());
        top = Some(found);
    }

    let top = top.ok_or_else(|| eyre!("no paths given"))?;
    Ok((top, rels))
}

/// The absolute path with symlinks resolved, also for a file that was deleted,
/// by resolving its deepest existing ancestor
fn real_path(path: &Path) -> Result<PathBuf> {
    let abs =
        std::path::absolute(path).wrap_err_with(|| format!("can't resolve {}", path.display()))?;

    let (base, rest) = abs
        .ancestors()
        .find_map(|dir| {
            let real = fs::canonicalize(dir).ok()?;
            Some((real, abs.strip_prefix(dir).ok()?.to_owned()))
        })
        .ok_or_else(|| eyre!("can't resolve {}", path.display()))?;

    // `..` after a missing directory can't be resolved without guessing
    if rest
        .components()
        .any(|part| !matches!(part, Component::Normal(_)))
    {
        bail!("can't resolve {}; pass a plain path", path.display());
    }

    Ok(base.join(rest))
}

fn toplevel(dir: &Path) -> Option<PathBuf> {
    let output = std::process::Command::new("git")
        .args(["rev-parse", "--show-toplevel"])
        .current_dir(dir)
        .output()
        .ok()?;

    if !output.status.success() {
        return None;
    }

    let top = String::from_utf8_lossy(&output.stdout).trim().to_owned();
    fs::canonicalize(top).ok()
}

/// The branch this checkout is on and the remote branch it syncs with
struct Upstream {
    branch: String,
    remote: String,
    /// The remote branch's ref, such as `refs/heads/master`
    merge: String,
    /// The remote-tracking ref, such as `refs/remotes/origin/master`
    tracking: String,
    /// The short name, such as `origin/master`
    name: String,
    /// Whether this is the default branch, which may push earlier unpushed commits
    on_default: bool,
}

impl Upstream {
    fn read(co: &Checkout) -> Result<Self> {
        let top = co.top.display();
        let branch = co
            .try_read(&["symbolic-ref", "--quiet", "--short", "HEAD"])
            .ok_or_else(|| {
                eyre!("detached HEAD in {top}; check out a branch with an upstream first")
            })?;

        let remote = co
            .try_read(&["config", &format!("branch.{branch}.remote")])
            .ok_or_else(|| {
                eyre!(
                    "branch {branch} has no upstream; set one with git branch -u, or commit \
                     from the default branch's checkout"
                )
            })?;

        if remote == "." {
            bail!("branch {branch} tracks a local branch; it needs a remote upstream");
        }

        let merge = co.read(&["config", &format!("branch.{branch}.merge")])?;
        let short = merge
            .strip_prefix("refs/heads/")
            .unwrap_or(&merge)
            .to_owned();
        let tracking = format!("refs/remotes/{remote}/{short}");
        let default = co
            .try_read(&[
                "symbolic-ref",
                "--quiet",
                &format!("refs/remotes/{remote}/HEAD"),
            ])
            .unwrap_or_else(|| format!("refs/remotes/{remote}/master"));

        Ok(Self {
            on_default: tracking == default && branch == short,
            name: format!("{remote}/{short}"),
            branch,
            remote,
            merge,
            tracking,
        })
    }
}

/// One checkout's top level and the shell that runs git in it
struct Checkout<'a> {
    sh: &'a Shell,
    top: PathBuf,
}

impl<'a> Checkout<'a> {
    /// git in this checkout, with pathspecs taken literally
    fn git(&self, args: &[&str]) -> xshell::Cmd<'a> {
        let top = &self.top;
        let sh = self.sh;
        cmd!(sh, "git -C {top} --literal-pathspecs {args...}")
    }

    fn read(&self, args: &[&str]) -> Result<String> {
        Ok(self.git(args).quiet().read()?)
    }

    fn try_read(&self, args: &[&str]) -> Option<String> {
        self.git(args)
            .quiet()
            .ignore_stderr()
            .read()
            .ok()
            .filter(|out| !out.is_empty())
    }

    /// A set of paths from a git command that lists file names, read with -z
    /// so unusual names are not quoted
    fn names(&self, args: &[&str]) -> Result<BTreeSet<String>> {
        let (subcommand, rest) = args
            .split_first()
            .ok_or_else(|| eyre!("no git subcommand"))?;
        let args = [&[*subcommand, "-z"][..], rest].concat();
        let out = self.git(&args).quiet().output()?;

        Ok(String::from_utf8_lossy(&out.stdout)
            .split('\0')
            .filter(|name| !name.is_empty())
            .map(str::to_owned)
            .collect())
    }

    fn rev(&self, rev: &str) -> Result<String> {
        self.read(&["rev-parse", rev])
    }

    fn short_head(&self) -> String {
        self.try_read(&["rev-parse", "--short", "HEAD"])
            .unwrap_or_default()
    }

    fn count(&self, range: &str) -> Result<u32> {
        let count = self.read(&["rev-list", "--count", range])?;
        count
            .parse()
            .wrap_err_with(|| format!("bad rev-list count {count:?}"))
    }

    fn is_ancestor(&self, ancestor: &str, rev: &str) -> bool {
        self.git(&["merge-base", "--is-ancestor", ancestor, rev])
            .quiet()
            .run()
            .is_ok()
    }

    fn is_tracked(&self, rel: &str) -> bool {
        self.git(&["ls-files", "--error-unmatch", "--", rel])
            .quiet()
            .ignore_stdout()
            .ignore_stderr()
            .run()
            .is_ok()
    }

    fn is_ignored(&self, rel: &str) -> bool {
        // check-ignore rejects --literal-pathspecs, so call git directly
        let top = &self.top;
        let sh = self.sh;
        cmd!(sh, "git -C {top} check-ignore -q {rel}")
            .quiet()
            .run()
            .is_ok()
    }

    fn git_path(&self, name: &str) -> Result<PathBuf> {
        let path = self.read(&["rev-parse", "--path-format=absolute", "--git-path", name])?;
        Ok(PathBuf::from(path))
    }

    fn unstage_all(&self) {
        let _ = self.git(&["restore", "--staged", "--", "."]).quiet().run();
    }
}

/// A checkout, the upstream it syncs with, and whether this is a dry run
struct Repo<'a> {
    co: Checkout<'a>,
    upstream: Upstream,
    dry: bool,
}

impl<'a> Repo<'a> {
    fn open(sh: &'a Shell, top: PathBuf, dry: bool) -> Result<Self> {
        let co = Checkout { sh, top };
        let upstream = Upstream::read(&co)?;
        Ok(Self { co, upstream, dry })
    }

    /// Whether the working-tree file has the same bytes as upstream's
    fn matches_upstream(&self, file: &str) -> bool {
        let ours = self.co.try_read(&["hash-object", "--", file]);
        let theirs = self
            .co
            .try_read(&["rev-parse", &format!("{}:{file}", self.upstream.tracking)]);
        ours.is_some() && ours == theirs
    }

    /// Refuses when another run or a person is mid-operation in this checkout
    fn check_idle(&self) -> Result<()> {
        for state in [
            "MERGE_HEAD",
            "rebase-merge",
            "rebase-apply",
            "CHERRY_PICK_HEAD",
        ] {
            if self.co.git_path(state)?.exists() {
                bail!(
                    "a merge, rebase or cherry-pick is in progress in {}; leave it to its owner",
                    self.co.top.display()
                );
            }
        }

        let staged = self.co.read(&["diff", "--cached", "--name-only"])?;
        if !staged.is_empty() {
            bail!(
                "these files are already staged by someone else; nothing was committed:\n{staged}"
            );
        }

        if self.co.try_read(&["config", "user.email"]).is_none() {
            bail!("git user.email is not set in {}", self.co.top.display());
        }

        Ok(())
    }

    /// Moves aside untracked files that upstream adds identically, and aborts
    /// before any change if one differs or upstream edits a file someone has
    /// dirty here, returning the dirty files that already match upstream
    fn clear_blockers(&self, rels: &[String]) -> Result<Vec<String>> {
        let up = &self.upstream.tracking;
        let incoming = self.co.names(&[
            "diff",
            "--name-only",
            "--no-renames",
            "--diff-filter=A",
            "HEAD",
            up,
        ])?;
        let untracked = self
            .co
            .names(&["ls-files", "--others", "--exclude-standard"])?;

        let (same, differ): (Vec<_>, Vec<_>) = incoming
            .intersection(&untracked)
            .cloned()
            .partition(|file| self.matches_upstream(file));

        if !differ.is_empty() {
            bail!(
                "untracked files differ from the versions {} adds; nothing was moved or \
                 committed. Compare and remove or rename them:\n{}",
                self.upstream.name,
                differ.join("\n")
            );
        }

        // a dirty tracked file already identical to upstream is a thread's edit
        // that was committed from another checkout; sync adopts it as is
        let changed = self
            .co
            .names(&["diff", "--name-only", "--no-renames", "HEAD", up])?;
        let mut ours_args = vec!["diff", "--name-only", "HEAD", "--"];
        ours_args.extend(rels.iter().map(String::as_str));
        let ours = self.co.names(&ours_args)?;
        let dirty = self.co.names(&["diff", "--name-only", "HEAD"])?;

        let (adopted, dirty_differ): (Vec<_>, Vec<_>) = dirty
            .difference(&ours)
            .filter(|file| changed.contains(*file))
            .cloned()
            .partition(|file| self.co.top.join(file).exists() && self.matches_upstream(file));

        if !dirty_differ.is_empty() {
            bail!(
                "these files have someone's uncommitted edits and {} changes them differently; \
                 this checkout can't sync until their owner commits or reverts them:\n{}",
                self.upstream.name,
                dirty_differ.join("\n")
            );
        }

        for file in &adopted {
            say(format!(
                "{file} already matches {}; adopting it as is",
                self.upstream.name
            ));
        }

        self.move_aside(&same)?;
        Ok(adopted)
    }

    fn move_aside(&self, files: &[String]) -> Result<()> {
        if files.is_empty() {
            return Ok(());
        }

        if !self.co.is_ignored(MOVED_DIR) {
            bail!(
                "{MOVED_DIR} is not gitignored in {}; can't move blockers aside safely",
                self.co.top.display()
            );
        }

        let stamp = chrono::Local::now().format("%Y-%m-%d-%H%M%S");
        let dest = format!("{MOVED_DIR}/{stamp}");

        for file in files {
            if self.dry {
                say(format!("would move identical untracked {file} to {dest}/"));
                continue;
            }

            let target = self.co.top.join(&dest).join(file);
            if let Some(parent) = target.parent() {
                fs::create_dir_all(parent)?;
            }

            fs::rename(self.co.top.join(file), &target)?;
            say(format!("moved identical untracked {file} to {dest}/{file}"));
        }

        Ok(())
    }

    fn commit(&self, rels: &[String], message: &Message) -> Result<()> {
        // a path moved aside above now arrives from upstream instead
        let keep: Vec<&str> = rels
            .iter()
            .filter(|rel| self.co.top.join(rel).exists() || self.co.is_tracked(rel))
            .map(String::as_str)
            .collect();

        if keep.is_empty() {
            say("nothing left to commit; syncing only");
            return Ok(());
        }

        if self.dry {
            say(format!("would commit \"{}\" with:", message.subject()));
            let status = self
                .co
                .read(&[&["status", "--short", "--"][..], &keep].concat())?;
            println!("{status}");
            return Ok(());
        }

        // the index was clean at the start, so anything staged on failure is
        // ours (or the commit hook's) and is safe to unstage
        let added = self
            .co
            .git(&[&["add", "-A", "--"][..], &keep].concat())
            .quiet()
            .run();
        if added.is_err() {
            self.co.unstage_all();
            bail!("git add failed; nothing was committed");
        }

        if self
            .co
            .read(&["diff", "--cached", "--name-only"])?
            .is_empty()
        {
            say("no changes in the given paths; syncing only");
            return Ok(());
        }

        let name = format!("user.name={AUTHOR}");
        let args = [
            &["-c", name.as_str(), "commit", "--quiet"][..],
            &message.args(),
        ]
        .concat();
        if self.co.git(&args).quiet().run().is_err() {
            self.co.unstage_all();
            bail!("git commit failed (see above); your paths are unstaged and uncommitted");
        }

        say(format!(
            "committed {} {}",
            self.co.short_head(),
            message.subject()
        ));
        Ok(())
    }

    /// Brings the checkout onto upstream, rebasing local commits elsewhere
    fn sync(&self, adopted: &[String]) -> Result<()> {
        let up = &self.upstream.tracking;
        let head = self.co.rev("HEAD")?;

        if self.co.is_ancestor(up, "HEAD") {
            return Ok(());
        }

        if self.dry {
            say(format!(
                "would rebase {} local commit(s) onto {} ({} new upstream)",
                self.co.count(&format!("{up}..HEAD"))?,
                self.upstream.name,
                self.co.count(&format!("HEAD..{up}"))?
            ));
            return Ok(());
        }

        let target = if self.co.is_ancestor("HEAD", up) {
            self.co.rev(up)?
        } else {
            self.rebase_elsewhere()?
        };

        // another thread may have committed here while the rebase ran
        if self.co.rev("HEAD")? != head {
            bail!("HEAD moved during the rebase; rerun cmd git commit-paths");
        }

        // staging a dirty file that already equals the target lets reset --keep
        // accept it without rewriting it
        if !adopted.is_empty() {
            let args: Vec<&str> = ["add", "--"]
                .into_iter()
                .chain(adopted.iter().map(String::as_str))
                .collect();
            self.co.git(&args).quiet().run()?;
        }

        if self
            .co
            .git(&["reset", "--quiet", "--keep", &target])
            .quiet()
            .run()
            .is_err()
        {
            if !adopted.is_empty() {
                let args: Vec<&str> = ["restore", "--staged", "--"]
                    .into_iter()
                    .chain(adopted.iter().map(String::as_str))
                    .collect();
                let _ = self.co.git(&args).quiet().run();
            }

            bail!(
                "couldn't move {} to the rebased commit without touching local changes; HEAD {} \
                 is committed but NOT pushed",
                self.co.top.display(),
                self.co.short_head()
            );
        }

        Ok(())
    }

    /// Rebases local commits onto upstream in a throwaway worktree, so a
    /// conflict never leaves the shared tree mid-rebase, and returns the result
    fn rebase_elsewhere(&self) -> Result<String> {
        let up = &self.upstream.tracking;
        let worktree = TempWorktree::add(self)?;
        let wt = worktree.path();
        let sh = self.co.sh;

        let rebased = cmd!(sh, "git -C {wt} rebase --quiet {up}")
            .quiet()
            .ignore_stdout()
            .ignore_stderr()
            .run();

        if rebased.is_err() {
            self.resolve_index_conflicts(wt)?;
        }

        let complete = cmd!(sh, "git -C {wt} merge-base --is-ancestor {up} HEAD")
            .quiet()
            .run();

        if complete.is_err() {
            bail!(
                "rebase onto {} did not complete; HEAD {} is committed but NOT pushed",
                self.upstream.name,
                self.co.short_head()
            );
        }

        let rebased = cmd!(sh, "git -C {wt} rev-parse HEAD").quiet().read()?;
        drop(worktree);
        Ok(rebased)
    }

    /// Continues a stopped rebase while only the generated INDEX.md conflicts,
    /// by regenerating it rather than merging it, and aborts otherwise
    fn resolve_index_conflicts(&self, wt: &Path) -> Result<()> {
        let sh = self.co.sh;
        let index_script = wt.join(".github/scripts/index.py");

        loop {
            let rebase_dir = cmd!(
                sh,
                "git -C {wt} rev-parse --path-format=absolute --git-path rebase-merge"
            )
            .quiet()
            .read()?;

            if !Path::new(&rebase_dir).is_dir() {
                return Ok(());
            }

            let conflicts = cmd!(sh, "git -C {wt} diff --name-only --diff-filter=U")
                .quiet()
                .read()?;

            if conflicts != "INDEX.md" || !index_script.is_file() {
                let _ = cmd!(sh, "git -C {wt} rebase --abort").quiet().run();
                let conflicts = if conflicts.is_empty() {
                    "(no conflicted files; the rebase stopped for another reason)".to_owned()
                } else {
                    conflicts
                };

                bail!(
                    "rebase onto {} conflicts in:\n{conflicts}\nCommitted locally as {} but NOT \
                     pushed; resolve by hand",
                    self.upstream.name,
                    self.co.short_head()
                );
            }

            let _dir = sh.push_dir(wt);
            if cmd!(sh, "python3 .github/scripts/index.py --write")
                .quiet()
                .run()
                .is_err()
            {
                say("warning: index.py reported problems (above)");
            }

            cmd!(sh, "git -C {wt} add INDEX.md").quiet().run()?;
            let _ = cmd!(sh, "git -C {wt} rebase --continue")
                .env("GIT_EDITOR", "true")
                .quiet()
                .ignore_stdout()
                .ignore_stderr()
                .run();
        }
    }

    /// Pushes, returning false when the remote rejects it
    fn push(&self) -> Result<bool> {
        if self.dry {
            say(format!("would push to {}:", self.upstream.name));
            let log = self.co.read(&[
                "log",
                "--oneline",
                &format!("{}..HEAD", self.upstream.tracking),
            ])?;
            println!("{log}");
            return Ok(true);
        }

        let refspec = format!("HEAD:{}", self.upstream.merge);
        let pushed = self
            .co
            .git(&["push", "--quiet", &self.upstream.remote, &refspec])
            .quiet()
            .run();

        Ok(pushed.is_ok())
    }
}

/// A lock per repository, so two runs never stage at once and sweep each
/// other's paths into one commit
struct Lock(PathBuf);

impl Lock {
    fn take(repo: &Repo) -> Result<Self> {
        let common = repo
            .co
            .read(&["rev-parse", "--path-format=absolute", "--git-common-dir"])?;
        let lock = Path::new(&common).join("commit-paths.lock");
        let pid_file = lock.join("pid");

        for _ in 0..LOCK_TRIES {
            if fs::create_dir(&lock).is_ok() {
                fs::write(&pid_file, std::process::id().to_string())?;
                return Ok(Self(lock));
            }

            // a killed run leaves its lock behind; take it over once that pid is gone
            let holder = fs::read_to_string(&pid_file)
                .ok()
                .and_then(|pid| pid.trim().parse::<i32>().ok());

            if holder.is_some_and(|pid| !process_alive(pid)) {
                let _ = fs::remove_dir_all(&lock);
                continue;
            }

            thread::sleep(Duration::from_secs(1));
        }

        bail!(
            "another commit-paths run has held {} for 2 minutes; remove it if no run is active",
            lock.display()
        )
    }
}

impl Drop for Lock {
    fn drop(&mut self) {
        let ours = fs::read_to_string(self.0.join("pid"))
            .is_ok_and(|pid| pid.trim() == std::process::id().to_string());

        if ours {
            let _ = fs::remove_dir_all(&self.0);
        }
    }
}

fn process_alive(pid: i32) -> bool {
    // signal 0 checks existence; EPERM still means the process is there
    let result = unsafe { libc::kill(pid, 0) };
    result == 0 || std::io::Error::last_os_error().raw_os_error() == Some(libc::EPERM)
}

/// A detached worktree of HEAD in a temporary directory, removed on drop
struct TempWorktree {
    top: PathBuf,
    dir: TempDir,
}

impl TempWorktree {
    fn add(repo: &Repo) -> Result<Self> {
        let dir = tempfile::Builder::new().prefix("commit-paths.").tempdir()?;
        let path = dir.path();
        repo.co
            .git(&["worktree", "add", "--quiet", "--detach"])
            .arg(path)
            .arg("HEAD")
            .quiet()
            .run()?;

        Ok(Self {
            top: repo.co.top.clone(),
            dir,
        })
    }

    fn path(&self) -> &Path {
        self.dir.path()
    }
}

impl Drop for TempWorktree {
    fn drop(&mut self) {
        let _ = std::process::Command::new("git")
            .arg("-C")
            .arg(&self.top)
            .args(["worktree", "remove", "--force"])
            .arg(self.dir.path())
            .output();
    }
}
